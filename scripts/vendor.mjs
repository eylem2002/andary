#!/usr/bin/env node
// Copies the browser libraries Andary needs from node_modules into public/vendor.
// The UI ships without a bundler (see docs/adr/0002-no-build-step.md), so the exact files the
// browser loads are committed. Re-run this after bumping three or the font packages.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');
const out = join(root, 'public', 'vendor');

const THREE_ADDONS = [
  'controls/MapControls.js',
  'controls/OrbitControls.js',
  'environments/RoomEnvironment.js',
  'geometries/RoundedBoxGeometry.js',
  'math/SimplexNoise.js',
  'postprocessing/EffectComposer.js',
  'postprocessing/RenderPass.js',
  'postprocessing/ShaderPass.js',
  'postprocessing/OutputPass.js',
  'postprocessing/UnrealBloomPass.js',
  'postprocessing/SMAAPass.js',
  'renderers/CSS2DRenderer.js',
  'shaders/FXAAShader.js',
  'shaders/HorizontalTiltShiftShader.js',
  'shaders/VerticalTiltShiftShader.js',
  'shaders/VignetteShader.js',
  'utils/BufferGeometryUtils.js',
];

const FONT_FACES = [
  { pkg: '@fontsource/overpass', family: 'Overpass', weights: [400, 600, 700, 800] },
  { pkg: '@fontsource/overpass-mono', family: 'Overpass Mono', weights: [400, 600] },
];

function copy(from, to) {
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
}

/** Copies an addon and, recursively, every relative module it imports. */
function copyAddon(rel, seen) {
  if (seen.has(rel)) return;
  seen.add(rel);
  const src = join(nm, 'three', 'examples', 'jsm', rel);
  copy(src, join(out, 'three', 'addons', rel));
  const code = readFileSync(src, 'utf8');
  for (const match of code.matchAll(/from\s+['"](\.{1,2}\/[^'"]+)['"]/g)) {
    const next = relative(join(nm, 'three', 'examples', 'jsm'), resolve(dirname(src), match[1]));
    copyAddon(next.split('\\').join('/'), seen);
  }
}

function vendorThree() {
  const build = join(nm, 'three', 'build');
  for (const file of ['three.module.js', 'three.core.js']) {
    copy(join(build, file), join(out, 'three', file));
  }
  copy(join(nm, 'three', 'LICENSE'), join(out, 'three', 'LICENSE'));
  const seen = new Set();
  for (const rel of THREE_ADDONS) copyAddon(rel, seen);
  return seen.size;
}

function vendorFonts() {
  const css = [];
  for (const { pkg, family, weights } of FONT_FACES) {
    const slug = pkg.split('/')[1];
    for (const weight of weights) {
      const file = `${slug}-latin-${weight}-normal.woff2`;
      copy(join(nm, pkg, 'files', file), join(out, 'fonts', file));
      css.push(
        `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${weight};` +
          `src:url('./${file}') format('woff2');}`,
      );
    }
    copy(join(nm, pkg, 'LICENSE'), join(out, 'fonts', `${slug}.LICENSE`));
  }
  writeFileSync(join(out, 'fonts', 'fonts.css'), `/* Generated by scripts/vendor.mjs. Fonts: SIL OFL 1.1 */\n${css.join('\n')}\n`);
}

if (!existsSync(join(nm, 'three'))) {
  console.error('node_modules/three is missing. Run `npm install` first.');
  process.exit(1);
}
rmSync(out, { recursive: true, force: true });
const addonCount = vendorThree();
vendorFonts();
console.log(`Vendored three.js core + ${addonCount} addon files and ${FONT_FACES.length} font families into public/vendor.`);
